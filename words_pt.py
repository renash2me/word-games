def pick_clue(entry, rng=None):
    """Escolhe uma dica aleatória da lista. Compatível com formato antigo."""
    if 'clues' in entry:
        clues = entry['clues']
        if not clues:
            return ''
        if len(clues) == 1:
            return clues[0]
        chooser = rng.choice if rng else random.choice
        return chooser(clues)
    return entry.get('clue', '')
